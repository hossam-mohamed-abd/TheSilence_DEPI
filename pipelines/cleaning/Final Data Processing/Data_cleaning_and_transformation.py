pharmacy = "chefaa"

input_file = f"downloads/{pharmacy}/{pharmacy}_ALL.csv"
output_file = f"downloads/{pharmacy}/{pharmacy}_CLEAN.csv"

# ============================
# Read CSV
# ============================

df = pd.read_csv(input_file)

print("Rows Before :", len(df))

# ======================================================
# Remove Unneeded Columns
# ======================================================

columns_to_drop = [
    "product_id",
    "url",
    "thumbnail_image",
    "availability",
    "specifications"
]

df.drop(
    columns=[c for c in columns_to_drop if c in df.columns],
    inplace=True
)

# ======================================================
# Rename Columns
# ======================================================

df.rename(columns={
    "name": "name_ar",
    "name_en": "name_en",
    "brand": "brand",
    "category": "category",
    "description": "description",
    "gallery_images": "gallery_images",
    "price": "price",
    "currency": "currency"
}, inplace=True)

# ======================================================
# Add Pharmacy Column
# ======================================================

df.insert(0, "pharmacy", pharmacy)

# ======================================================
# General Text Cleaning
# ======================================================

text_columns = [
    "name_ar",
    "name_en",
    "brand",
    "category",
    "description"
]

for col in text_columns:

    if col in df.columns:

        df[col] = (
            df[col]
            .fillna("")
            .astype(str)
            .str.replace("\n", " ", regex=False)
            .str.replace("\t", " ", regex=False)
            .str.replace("|", " ", regex=False)
            .str.replace(r"\s+", " ", regex=True)
            .str.strip()
        )

# ======================================================
# Clean Category
# Keep Last Category Only
# ======================================================

def clean_category(cat):

    if pd.isna(cat):
        return ""

    parts = [x.strip() for x in str(cat).split(">") if x.strip()]

    if len(parts):
        return parts[-1]

    return ""

df["category"] = df["category"].apply(clean_category)

# ======================================================
# Clean Description
# ======================================================

def clean_description(desc, brand):

    if pd.isna(desc):
        return ""

    desc = str(desc)

    # Remove repeated headings
    remove_words = [
        "مميزات المنتج",
        "عن هذا المنتج"
    ]

    for w in remove_words:
        desc = desc.replace(w, "")

    # Remove brand name
    if pd.notna(brand):

        brand = str(brand).strip()

        if brand != "":
            desc = re.sub(
                re.escape(brand),
                "",
                desc,
                flags=re.IGNORECASE
            )

    desc = re.sub(r"\s+", " ", desc)

    return desc.strip()

df["description"] = df.apply(
    lambda row: clean_description(
        row["description"],
        row["brand"]
    ),
    axis=1
)

# ======================================================
# Clean English Name
# ======================================================

def clean_name_en(name):

    if pd.isna(name):
        return ""

    # Decode URL Encoding
    name = unquote(str(name))

    name = name.lower()

    # remove product codes
    name = re.sub(r"\b[a-z0-9_]{4,}\b$", "", name)

    # remove sizes
    name = re.sub(
        r"\b\d+(\.\d+)?\s?(ml|gm|g|mg|kg|l|mcg)\b",
        "",
        name,
        flags=re.IGNORECASE
    )

    # remove extra spaces
    name = re.sub(r"\s+", " ", name)

    return name.strip()

df["name_en"] = df["name_en"].apply(clean_name_en)

# ======================================================
# Clean Brand
# ======================================================

df["brand"] = (
    df["brand"]
    .str.strip()
    .str.replace(r"\s+", " ", regex=True)
)

# ======================================================
# Price
# ======================================================

df["price"] = pd.to_numeric(
    df["price"],
    errors="coerce"
)

# ======================================================
# Remove Empty Names
# ======================================================

df = df[
    df["name_en"] != ""
]

# ======================================================
# Remove Duplicate Products
# ======================================================

df.drop_duplicates(
    subset=[
        "name_en",
        "brand",
        "price"
    ],
    inplace=True
)

# ======================================================
# Reorder Columns
# ======================================================

final_columns = [
    "pharmacy",
    "name_ar",
    "name_en",
    "brand",
    "category",
    "description",
    "gallery_images",
    "price",
    "currency"
]

df = df[final_columns]

# ======================================================
# Save
# ======================================================

os.makedirs(
    os.path.dirname(output_file),
    exist_ok=True
)

df.to_csv(
    output_file,
    index=False,
    encoding="utf-8-sig"
)

print("Rows After :", len(df))
print("Saved To :", output_file)

