def clean_category(text):

    if pd.isna(text):
        return ""

    text = str(text)

    text = text.strip()

    text = text.lower()

    text = text.replace("_", " ")
    text = text.replace("-", " ")
    text = text.replace("&", " and ")

    text = re.sub(r"\s+", " ", text)

    return text

# ==========================================================
# ENGLISH CHECK
# ==========================================================

def is_english(text):

    if text == "":
        return False

    return bool(re.search(r"[A-Za-z]", text))

# ==========================================================
# DISPLAY FORMAT
# ==========================================================

def display_category(text):

    words = clean_category(text).split()

    return " ".join(word.capitalize() for word in words)

