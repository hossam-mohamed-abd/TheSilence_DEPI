def tokenize(text):

    if pd.isna(text):
        return []

    text = str(text).lower()

    text = re.sub(r"[^a-z0-9 ]", " ", text)

    text = re.sub(r"\s+", " ", text).strip()

    return text.split()

# ==========================================================
# NAME SCORE
# ==========================================================

def calculate_name_score(name, common_words, pharmacy):

    score = 0

    tokens = tokenize(name)

    # عدد الكلمات
    score += len(tokens) * 2

    # الكلمات المشتركة
    for token in tokens:

        score += common_words.get(token, 0) * 5

    # أولوية الصيدلية
    score += PHARMACY_PRIORITY.get(str(pharmacy).lower(), 0) * 10

    # خصم لو الاسم فيه %
    if "%" in str(name):
        score -= 10

    # خصم لو فيه URL Encoding
    if "%d" in str(name).lower():
        score -= 30

    return score

