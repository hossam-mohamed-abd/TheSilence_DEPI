class UnionFind:

    def __init__(self):

        self.parent = {}

    def add(self, x):

        if x not in self.parent:

            self.parent[x] = x

    def find(self, x):

        if self.parent[x] != x:

            self.parent[x] = self.find(self.parent[x])

        return self.parent[x]

    def union(self, a, b):

        ra = self.find(a)

        rb = self.find(b)

        if ra != rb:

            self.parent[rb] = ra

