import os
import boto3
import pandas as pd

# =============================
# S3 Connection
# =============================



BUCKET = "DEPI-data-lake"

pharmacies = [
    "aldawaaegy",
    "bloom",
    "chefaa",
    "gardenia"
]

base_output = "downloads"

for pharmacy in pharmacies:

    print("=" * 60)
    print(f"Processing {pharmacy}")
    print("=" * 60)

    prefix = f"raw/pharmacies/{pharmacy}/"

    response = s3.list_objects_v2(
        Bucket=BUCKET,
        Prefix=prefix
    )

    csv_files = [
        obj["Key"]
        for obj in response.get("Contents", [])
        if obj["Key"].endswith(".csv")
    ]

    print(f"Found {len(csv_files)} files")

    output_folder = os.path.join(base_output, pharmacy)
    os.makedirs(output_folder, exist_ok=True)

    all_data = []

    for key in csv_files:

        filename = os.path.basename(key)
        local_file = os.path.join(output_folder, filename)

        print(f"Downloading: {filename}")

        s3.download_file(
            BUCKET,
            key,
            local_file
        )

        try:
            df = pd.read_csv(local_file)

            all_data.append(df)

        except Exception as e:
            print(f"Error reading {filename}: {e}")

        if os.path.exists(local_file):
            os.remove(local_file)

    if len(all_data) == 0:
        print(f"No data found for {pharmacy}")
        continue

    merged_df = pd.concat(all_data, ignore_index=True)

    output_file = os.path.join(
        output_folder,
        f"{pharmacy}_ALL.csv"
    )

    merged_df.to_csv(
        output_file,
        index=False,
        encoding="utf-8-sig"
    )

    print(f"Saved: {output_file}")
    print(f"Rows: {len(merged_df)}")

    del merged_df
    del all_data

print("\nAll pharmacies processed successfully.")

