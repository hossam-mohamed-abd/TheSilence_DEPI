def clean_brand(text):

    if pd.isna(text):
        return ""

    text = str(text)

    text = text.strip()

    text = re.sub(r"\s+", " ", text)

    text = re.sub(r"[^\w\s&+.'/-]", "", text)

    return text

# ==========================================================
# ENGLISH CHECK
# ==========================================================

def is_english(text):

    if text == "":
        return False

    return bool(re.search(r"[A-Za-z]", text))

# ==========================================================
# NORMALIZE CASE
# ==========================================================

def normalize_key(text):

    text = clean_brand(text)

    return text.lower()

# ==========================================================
# DISPLAY FORMAT
# ==========================================================

def display_brand(text):

    text = clean_brand(text)

    return text.title()

